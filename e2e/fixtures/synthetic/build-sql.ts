/**
 * Generates the synthetic dataset as plain SQL (no driver needed), so any build of the app can load it onto the
 * frozen schema (00-schema-lookups.sql). Usage: `npx tsx fixtures/synthetic/build-sql.ts <out.sql>`.
 * Output is deterministic: running it twice yields byte-identical files.
 */
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

import { categoriesEvents, contacts, events, eventsTools, files, honoraria, registrations } from './catalog';

type Row = Record<string, string | number | null>;

function lit(v: string | number | null): string {
  if (v === null) return 'NULL';
  if (typeof v === 'number') return String(v);
  const esc = v
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n')
    .replace(/\0/g, '\\0');
  return `'${esc}'`;
}

function insert(table: string, rows: Row[]): string {
  return rows
    .map((r) => {
      const cols = Object.keys(r);
      return `INSERT INTO \`${table}\` (${cols.map((c) => `\`${c}\``).join(', ')}) VALUES (${cols.map((c) => lit(r[c])).join(', ')});`;
    })
    .join('\n');
}

export function buildSql(): string {
  // Join tables have an auto-increment id; assign deterministic ones.
  const ce = categoriesEvents.map((r, i) => ({ id: i + 1, ...r }));
  const et = eventsTools.map((r, i) => ({ id: i + 1, ...r }));
  return [
    '-- Synthetic dataset (generated by e2e/fixtures/synthetic/build-sql.ts). Do not edit by hand.',
    'SET NAMES utf8mb3;',
    'SET FOREIGN_KEY_CHECKS=0;',
    insert('contacts', contacts),
    insert('events', events),
    insert('categories_events', ce),
    insert('events_tools', et),
    insert('registrations', registrations),
    insert('files', files),
    insert('honoraria', honoraria),
    'SET FOREIGN_KEY_CHECKS=1;',
    '',
  ].join('\n');
}

export const sha256 = (s: string) => createHash('sha256').update(s).digest('hex');

if (process.argv[1] && process.argv[1].endsWith('build-sql.ts')) {
  const out = process.argv[2];
  const sqlText = buildSql();
  if (out) {
    writeFileSync(out, sqlText, { encoding: 'utf8' });
    console.log(`wrote ${out} (${sqlText.length} bytes, sha256 ${sha256(sqlText)})`);
  } else {
    process.stdout.write(sqlText);
  }
}
